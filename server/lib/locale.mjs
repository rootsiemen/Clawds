export function tr(s, p) {
  let r = lang === 'ru' ? s : (lang === 'en' ? EN : ES)[s] ?? s
  if (p) r = r.replace(/\{(\w+)\}/g, (_, k) => String(p[k] ?? ''))
  return r
}
