// Просьба к Haiku: придумать навык (skill) по запросу человека. Ответ: один JSON-объект.
export function generateSkillPrompt(request, lang = 'ru') {
  const en = lang === 'en'
  const es = lang === 'es'
  // Шаблон ответа сам написан на нужном языке: иначе модель переходит на английский
  const tpl = en
    ? '{"name": "<short-latin-name-with-dashes>", "description": "<in English: what the skill does and WHEN to use it, 1-2 sentences>", "body": "<in English: Markdown instructions, 5-10 numbered steps>"}'
    : es
      ? '{"name": "<short-latin-name-with-dashes>", "description": "<en español: qué hace la habilidad y CUÁNDO usarla, 1-2 frases>", "body": "<en español: instrucciones en Markdown, 5-10 pasos numerados>"}'
      : '{"name": "<короткое-латинское-имя-через-дефис>", "description": "<по-русски: что навык делает и КОГДА его использовать, 1-2 предложения>", "body": "<по-русски: инструкция в Markdown, 5-10 нумерованных шагов>"}'
  return 'Составь навык (skill) для ИИ-агента по запросу человека.\n' +
    'Запрос: ' + request + '\n\n' +
    'Верни ТОЛЬКО один JSON-объект, без пояснений и без блоков кода, по этому шаблону:\n' + tpl + '\n\n' +
    'Правила: по description агент решает, подходит ли навык, поэтому он конкретный. В body: что проверить в начале, как действовать, в каком виде отчитаться, чего не делать. Без воды. ' +
    (en ? 'Write description and body in English.' : 'Поля description и body пиши ПО-РУССКИ, не по-английски. Только name латиницей.')
}
